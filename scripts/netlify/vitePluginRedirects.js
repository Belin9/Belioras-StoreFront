/* Netlify Redirects */

import fs from "node:fs";
import path from "node:path";

/**
 * Writes `dist/_redirects` at build time, so the API's address is a setting
 * rather than something baked into a file in public/.
 *
 * The client always calls a relative `/api` and Netlify proxies it to
 * `API_ORIGIN`. Keeping one origin is what keeps the refresh cookie
 * first-party (Safari drops it otherwise) and avoids CORS preflights, so
 * switching APIs means changing this one value, never the client code.
 *
 * `API_ORIGIN` comes from, highest priority first: the Netlify site's
 * environment variables, `.env.production.local`, then `.env.production`
 * (committed, holds the live default).
 */
export default function netlifyRedirects(apiOrigin) {
  let outDir;
  return {
    name: "belioras-netlify-redirects",
    apply: "build",

    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir);
    },

    closeBundle() {
      const origin = checkedOrigin(apiOrigin);
      const rules = [
        "# Generated by scripts/netlify/vitePluginRedirects.js from API_ORIGIN. Do not edit dist/_redirects.",
        "# The proxy must come before the SPA fallback, or /api calls are answered with index.html.",
        `/api/*  ${origin}/api/:splat  200!`,
        "# Public pages have their own HTML file (built by scripts/seo), served before",
        "# this rule; every other address gets the neutral app shell.",
        "/*      /app.html  200",
        "",
      ];
      fs.writeFileSync(path.join(outDir, "_redirects"), rules.join("\n"));
      console.log(`belioras-netlify: /api proxied to ${origin}`);
    },
  };
}

/** The origin alone (scheme + host), or a build error that says what to fix. */
function checkedOrigin(value) {
  const help = "Set API_ORIGIN (e.g. https://api.example.com) in client/.env.production or the Netlify site's environment variables.";
  if (!value?.trim()) throw new Error(`belioras-netlify: API_ORIGIN is not set. ${help}`);
  let url;
  try {
    url = new URL(value.trim());
  } catch {
    throw new Error(`belioras-netlify: API_ORIGIN "${value}" is not a URL. ${help}`);
  }
  if (url.protocol !== "https:") throw new Error(`belioras-netlify: API_ORIGIN must use https, got "${value}".`);
  if (url.pathname !== "/" || url.search || url.hash) {
    throw new Error(`belioras-netlify: API_ORIGIN must be the origin only, without a path (/api is added for you), got "${value}".`);
  }
  return url.origin;
}
